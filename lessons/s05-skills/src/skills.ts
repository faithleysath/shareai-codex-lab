export const SKILLS: SkillDefinition[] = [FORTUNE_TELLER_SKILL, FISHING_GUIDE_SKILL];

export function getSkillNames(): SkillName[] {
  return SKILLS.map((skill) => skill.name);
}

export function getSkillByName(name: string): SkillDefinition | null {
  return SKILLS.find((skill) => skill.name === name) ?? null;
}

export function buildSkillIndexText(): string {
  return SKILLS.map((skill) =>
    [
      `- ${skill.name} (${skill.title})`,
      `  summary: ${skill.summary}`,
      `  trigger hints: ${skill.triggerHints.join(", ")}`,
    ].join("\n"),
  ).join("\n");
}
